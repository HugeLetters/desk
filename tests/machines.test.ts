/** Every state `reconcile` goes through from `initial` on `events`, `initial` first. */
const walk = <S, E>(reconcile: (state: S, event: E) => S, initial: S, events: ReadonlyArray<E>) =>
	Arr.scan(events, initial, reconcile);

/** Each step of a walk: the state before, the event, the state after. */
const steps = <S, E>(reconcile: (state: S, event: E) => S, initial: S, events: ReadonlyArray<E>) => {
	const states = walk(reconcile, initial, events);
	return events.map((event, index) => ({
		before: states[index] ?? initial,
		event,
		after: states[index + 1] ?? initial,
	}));
};

/** Events generated by tag, from `make`. */
const events = <E>(tags: ReadonlyArray<string>, make: (tag: string, n: number) => E) =>
	Arbitrary.array(
		Arbitrary.map(
			Arbitrary.all({
				tag: Arbitrary.schema(Schema.Literals(tags as [string, ...Array<string>])),
				n: Arbitrary.schema(Schema.Int.check(Schema.isBetween({ minimum: 1, maximum: 99_999 }))),
			}),
			({ tag, n }) => make(tag, n),
		),
		{ maxLength: 80 },
	);

// The actor.

type Light = "off" | "on" | "fired";

test("a state's run starts on entering it and is interrupted on leaving; what it emits after is dropped", async () => {
	const seen = await Effect.runPromise(
		Effect.scoped(
			Effect.gen(function* () {
				const actor = yield* Machine.start<Light, "toggle" | "fire", never>({
					initial: "off",
					// Firing moves any state: only dropping it keeps a stale timer out of the state after.
					reconcile: (state, event) => (event === "fire" ? "fired" : state === "off" ? "on" : "off"),
					// While on, a timer that can't be stopped once it starts: it still emits after `on` is left.
					run: (state, emit) =>
						state === "on"
							? Effect.uninterruptible(Effect.andThen(Effect.sleep("30 millis"), emit("fire")))
							: Effect.void,
				});
				yield* actor.send("toggle");
				yield* Effect.sleep("5 millis");
				yield* actor.send("toggle");
				yield* Effect.sleep("60 millis");
				const afterStale = yield* actor.state;
				yield* actor.send("toggle");
				const fired = yield* Effect.timeoutOption(
					actor.when((state) => (state === "fired" ? Option.some(state) : Option.none())),
					"200 millis",
				);
				return { afterStale, fired: Option.isSome(fired) };
			}),
		),
	);
	expect(seen).toEqual({ afterStale: "off", fired: true });
});

test("an event that changes nothing leaves the state's run going", async () => {
	const starts = await Effect.runPromise(
		Effect.scoped(
			Effect.gen(function* () {
				const started: Array<number> = [];
				const actor = yield* Machine.start<number, "same" | "next", never>({
					initial: 0,
					reconcile: (state, event) => (event === "next" ? state + 1 : state),
					run: (state) => Effect.sync(() => started.push(state)),
				});
				yield* Effect.forEach(["same", "same", "next", "same"] as const, actor.send, { discard: true });
				yield* actor.when((state) => (state === 1 ? Option.some(state) : Option.none()));
				yield* Effect.sleep("10 millis");
				return started;
			}),
		),
	);
	expect(starts).toEqual([0, 1]);
});

test("states with the same key share one run, started in the first of them; another key starts another", async () => {
	const starts = await Effect.runPromise(
		Effect.scoped(
			Effect.gen(function* () {
				const started: Array<number> = [];
				const actor = yield* Machine.start<number, "next", never>({
					initial: 0,
					reconcile: (state) => state + 1,
					// 0 and 1 are one key, 2 and 3 another.
					key: (state) => Math.floor(state / 2),
					run: (state) => Effect.sync(() => started.push(state)),
				});
				yield* Effect.forEach([1, 2, 3], () => actor.send("next"), { discard: true });
				yield* actor.when((state) => (state === 3 ? Option.some(state) : Option.none()));
				yield* Effect.sleep("10 millis");
				return started;
			}),
		),
	);
	expect(starts).toEqual([0, 2]);
});

// The plugin's connection.

const client = {} as Connection.Client;
const connectionEvents = events(["On", "Off", "Hello", "Dropped", "Outdated", "Retry"], (tag, n): Connection.Event => {
	switch (tag) {
		case "On":
		case "Off":
			return Connection.Event.Want({ on: tag === "On" });
		case "Hello":
			return Connection.Event.Hello({ client, url: `http://127.0.0.1:${n}/` });
		case "Dropped":
		case "Outdated":
			return { _tag: tag, message: `why ${n}` };
		default:
			return Connection.Event.Retry();
	}
});
const connectionSteps = (sequence: ReadonlyArray<Connection.Event>) =>
	steps(Connection.reconcile, Connection.State.Off(), sequence);

test("connection: off only when not wanted, and always then; live only by hello while connecting", async () => {
	await check(connectionEvents, (sequence) =>
		connectionSteps(sequence).every(({ before, event, after }) => {
			if (event._tag === "Want" && !event.on) return after._tag === "Off";
			if (after._tag === "Off") return before._tag === "Off";
			if (after._tag === "Live" && before._tag !== "Live")
				return before._tag === "Connecting" && event._tag === "Hello" && after.url === event.url;
			return true;
		}),
	);
});

test("connection: refused only by an outdated plugin, and for good until turned off; a dropped link backs off, then retries", async () => {
	await check(connectionEvents, (sequence) =>
		connectionSteps(sequence).every(({ before, event, after }) => {
			if (before._tag === "Refused") return after === before || after._tag === "Off";
			if (after._tag === "Refused") return before._tag === "Connecting" && event._tag === "Outdated";
			if (after._tag === "Backoff" && before._tag !== "Backoff")
				return (before._tag === "Connecting" || before._tag === "Live") && event._tag === "Dropped";
			if (before._tag === "Backoff" && after._tag !== "Backoff")
				return (after._tag === "Connecting" && event._tag === "Retry") || after._tag === "Off";
			return true;
		}),
	);
});

test("connection: one link from connecting through live; every other change of state is a new run", async () => {
	await check(connectionEvents, (sequence) =>
		connectionSteps(sequence).every(({ before, after }) => {
			const same = Connection.key(before) === Connection.key(after);
			return before._tag === after._tag || (before._tag === "Connecting" && after._tag === "Live") ? same : !same;
		}),
	);
});

// Delivery: one machine per due message.

const deliveryEvents = events(
	["Delivered", "Unknown", "Failed", "Retry"],
	(tag, n): Delivery.Event =>
		tag === "Failed"
			? Delivery.Event.Failed({ failure: new DeliveryFailed({ session: S("ses_a"), cause: `cause ${n}` }) })
			: ({ _tag: tag } as Delivery.Event),
);

test("delivery: delivered only by a send that went in, and for good; a waiting message shows why its last try failed, and only a retry sends it again", async () => {
	await check(deliveryEvents, (sequence) =>
		steps(Delivery.reconcile, Delivery.State.Sending(), sequence).every(({ before, event, after }) => {
			if (before._tag === "Delivered") return after === before;
			if (after._tag === "Delivered") return before._tag === "Sending" && event._tag === "Delivered";
			if (after._tag === "Waiting" && before._tag === "Sending")
				return event._tag === "Failed"
					? after.failure === event.failure
					: event._tag === "Unknown" && after.failure === undefined;
			if (after._tag === "Sending" && before._tag === "Waiting") return event._tag === "Retry";
			return after === before;
		}),
	);
});

// Clients.

const clientEvents = events(["Joined", "Left", "Elapsed", "Retire"], (tag) =>
	Clients.Event.$match({ _tag: tag } as Clients.Event, {
		Joined: () => Clients.Event.Joined(),
		Left: () => Clients.Event.Left(),
		Elapsed: () => Clients.Event.Elapsed(),
		Retire: () => Clients.Event.Retire(),
	}),
);
const clientSteps = (sequence: ReadonlyArray<Clients.Event>) =>
	steps(Clients.reconcile, Clients.State.Quiet(), sequence);

test("clients: the count is joins less leaves, Busy only with some; Done for good, idle only from Quiet's timer", async () => {
	await check(clientEvents, (sequence) =>
		clientSteps(sequence).every(({ before, event, after }) => {
			if (before._tag === "Done") return after === before;
			if (event._tag === "Retire") return after._tag === "Done" && after.why === "retired";
			if (after._tag === "Done") return after.why === "idle" && before._tag === "Quiet" && event._tag === "Elapsed";
			const count = (state: Clients.State) => (state._tag === "Busy" ? state.clients : 0);
			const expected =
				event._tag === "Joined"
					? count(before) + 1
					: event._tag === "Left"
						? Math.max(0, count(before) - 1)
						: count(before);
			return count(after) === expected && (after._tag !== "Busy" || after.clients > 0);
		}),
	);
});

// Registration.

const registrationEvents = events(
	["Created", "Exists", "Held", "Stale", "Contended", "Failed", "Retry"],
	(tag, pid): Registration.Event =>
		tag === "Held" ? Registration.Event.Held({ pid }) : ({ _tag: tag } as Registration.Event),
);
const attempt = (state: Registration.State) => ("attempt" in state ? state.attempt : undefined);

test("registration: Registered only by creating the file; Taken only after the last try; both for good", async () => {
	await check(registrationEvents, (sequence) =>
		steps(Registration.reconcile, Registration.State.Creating({ attempt: 0 }), sequence).every(
			({ before, event, after }) => {
				if (before._tag === "Registered" || before._tag === "Taken") return after === before;
				if (after._tag === "Registered")
					return event._tag === "Created" && (before._tag === "Creating" || before._tag === "Replacing");
				if (after._tag === "Taken") return attempt(before) === Registration.attempts - 1;
				// Tries only ever go up, one at a time, and only by waiting first.
				const step = (attempt(after) ?? 0) - (attempt(before) ?? 0);
				return step === 0 || (step === 1 && before._tag === "Waiting" && after._tag === "Creating");
			},
		),
	);
});

test("registration: a holder that's alive, or another service replacing, means waiting; the pid is the one last seen", async () => {
	await check(registrationEvents, (sequence) =>
		steps(Registration.reconcile, Registration.State.Creating({ attempt: 0 }), sequence).every(
			({ before, event, after }) => {
				const active = before._tag === "Creating" || before._tag === "Checking" || before._tag === "Replacing";
				if (!active || !["Held", "Contended", "Failed"].includes(event._tag)) return true;
				const pid = event._tag === "Held" ? event.pid : 0;
				return (after._tag === "Waiting" || after._tag === "Taken") && after.pid === pid;
			},
		),
	);
});

test("registration: whatever happens, a service that keeps being turned away is Taken after the last try", () => {
	const turnedAway = Array.from({ length: Registration.attempts }, () => [
		Registration.Event.Exists(),
		Registration.Event.Held({ pid: 7 }),
		Registration.Event.Retry(),
	]).flat();
	const states = walk(Registration.reconcile, Registration.State.Creating({ attempt: 0 }), turnedAway);
	expect(states.at(-1)).toEqual(Registration.State.Taken({ pid: 7 }));
	expect(states.filter((state) => state._tag === "Checking")).toHaveLength(Registration.attempts);
});
